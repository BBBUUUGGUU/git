def settext(p,text):
    rp=deepcopy(p.runs[0]._r.rPr) if p.runs else None
    p.clear()
    r=p.add_run(text)
    if rp is not None:r._r.insert(0,rp)
    return r

def comment(p,text):
    d.add_comment(p.runs[:1],text=text,author='补写说明',initials='说明')

def fill(index,texts,note=None):
    p=ps[index]
    for j,text in enumerate(texts):
        if j:
            el=OxmlElement('w:p');p._p.addnext(el);p=Paragraph(el,p._parent)
        else:
            p.clear()
        if p._p.pPr is not None:p._p.remove(p._p.pPr)
        p._p.insert(0,deepcopy(body))
        r=p.add_run(text)
        if rpr is not None:r._r.insert(0,deepcopy(rpr))
        if j==0 and note:comment(p,note)

